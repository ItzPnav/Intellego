import os
import httpx
import re
from typing import AsyncGenerator, Dict, Any, List, Optional
from dotenv import load_dotenv, find_dotenv

load_dotenv(find_dotenv())

NEMOTRON_API_KEY = os.getenv("NEMOTRON_API_KEY") or os.getenv("NVIDIA_API_KEY") or ""
API_URL = os.getenv("NVIDIA_API_URL", "https://integrate.api.nvidia.com/v1/chat/completions")
MODEL_NAME = os.getenv("NEMOTRON_MODEL", "nvidia/nemotron-3.5-lightning-30b-a3b")

def parse_proposed_changes(text: str) -> List[Dict[str, str]]:
    """Parse XML-like proposed change blocks from agent text.
    Format:
    <proposed_change file="relative/path">
    content
    </proposed_change>
    """
    pattern = re.compile(r'<proposed_change[^>]*\bfile=["\']([^"\']+)["\'][^>]*>(.*?)</proposed_change>', re.DOTALL | re.IGNORECASE)
    matches = pattern.findall(text)
    
    changes = []
    for filepath, content in matches:
        # Strip leading/trailing newlines that might be added by formatting
        clean_content = content.lstrip("\n").rstrip("\n")
        changes.append({
            "filePath": filepath.strip(),
            "content": clean_content
        })
    return changes

def clean_agent_response(text: str) -> str:
    """Remove proposed change blocks from the user-facing text to keep it clean."""
    pattern = re.compile(r'<proposed_change[^>]*\bfile=["\']([^"\']+)["\'][^>]*>(.*?)</proposed_change>', re.DOTALL | re.IGNORECASE)
    cleaned = pattern.sub(r"[Proposed changes generated for `\1`. Review them in the preview panel.]", text)
    # Also remove raw __INTELLEGO_PREVIEW_JSON__ token if present in text
    cleaned = re.sub(r'\n*__INTELLEGO_PREVIEW_JSON__:[^\n]*', '', cleaned)
    return cleaned.strip()

async def call_nemotron_stream(
    messages: List[Dict[str, str]], 
    workspace_files: List[str]
) -> AsyncGenerator[str, None]:
    """Call the NVIDIA Nemotron API or stream Mock response if no key is configured."""
    
    # Context injected as system prompt
    file_list_str = "\n".join([f"- {f}" for f in workspace_files])
    
    system_prompt = (
        "You are Intellego's Agent Runtime (Planner -> Coder -> Reviewer), a local-first AI software engineer.\n"
        "You have access to the user's workspace files. Below is the list of files in the workspace:\n"
        f"{file_list_str}\n\n"
        "Rules:\n"
        "1. If you need to write or edit a file, you MUST output the complete proposed content inside a `<proposed_change>` block.\n"
        "Example:\n"
        "<proposed_change file=\"utils.py\">\n"
        "def add(a, b):\n"
        "    return a + b\n"
        "</proposed_change>\n"
        "2. Do not use markdown backticks around the XML block itself.\n"
        "3. Write production-ready code. Be clear, clean, and helpful.\n"
    )
    
    full_messages = [{"role": "system", "content": system_prompt}] + messages
    
    if not NEMOTRON_API_KEY:
        # Mock Response for Demo Mode
        yield "⚠️ **NEMOTRON_API_KEY not found in environment.** Running in **Mock Demo Mode**.\n\n"
        
        last_user_message = messages[-1]["content"] if messages else ""
        
        if any(kw in last_user_message.lower() for kw in ["create", "write", "make", "add", "build"]):
            # Guessing file name from query
            match = re.search(r'\b([\w\-]+\.\w+)\b', last_user_message)
            filename = match.group(1) if match else "demo_file.py"
            
            yield f"I've planned your change. Let's create a new file named `{filename}` in the workspace:\n\n"
            
            proposed_block = (
                f'<proposed_change file="{filename}">\n'
                f'# Demo file generated by Intellego Mock Agent\n'
                f'# Requested by user: "{last_user_message}"\n\n'
                f'def hello_world():\n'
                f'    print("Welcome to Intellego local-first AI workspace!")\n\n'
                f'if __name__ == "__main__":\n'
                f'    hello_world()\n'
                f'</proposed_change>\n'
            )
            
            for line in proposed_block.splitlines(keepends=True):
                yield line
                
            yield f"\nCreated preview for `{filename}`. Please review it on the right and click **Accept** to write it to disk!"
        else:
            yield f"Hello! You said: *\"{last_user_message}\"*\n\nSince no API Key is configured, I am running in demo mode. Ask me to \"create a file\" (e.g. *create test.js*) to try out the file edit and preview loop!"
        return

    # Call NVIDIA Build API
    headers = {
        "Authorization": f"Bearer {NEMOTRON_API_KEY}",
        "Content-Type": "application/json"
    }
    payload = {
        "model": MODEL_NAME,
        "messages": full_messages,
        "temperature": 0.2,
        "max_tokens": 4096,
        "stream": True,
        "chat_template_kwargs": {"thinking": False}
    }
    
    timeout_cfg = httpx.Timeout(90.0, connect=15.0, read=90.0)
    try:
        async with httpx.AsyncClient(timeout=timeout_cfg) as client:
            async with client.stream("POST", API_URL, headers=headers, json=payload) as stream_resp:
                if stream_resp.status_code == 400:
                    error_bytes = await stream_resp.aread()
                    error_str = error_bytes.decode('utf-8', errors='ignore')
                    if "chat_template_kwargs" in error_str:
                        payload.pop("chat_template_kwargs", None)
                        async with client.stream("POST", API_URL, headers=headers, json=payload) as retry_resp:
                            if retry_resp.status_code != 200:
                                retry_err = await retry_resp.aread()
                                yield f"Error calling NVIDIA API (status {retry_resp.status_code}): {retry_err.decode('utf-8')}"
                                return
                            async for line in retry_resp.aiter_lines():
                                if not line:
                                    continue
                                if line.startswith("data: "):
                                    data_str = line[6:]
                                    if data_str.strip() == "[DONE]":
                                        break
                                    try:
                                        import json
                                        chunk_json = json.loads(data_str)
                                        choices = chunk_json.get("choices", [])
                                        if choices:
                                            delta = choices[0].get("delta", {})
                                            token = delta.get("content") or delta.get("reasoning_content") or ""
                                            if token:
                                                yield token
                                    except Exception:
                                        pass
                        return
                    else:
                        yield f"Error calling NVIDIA API (status 400): {error_str}"
                        return
                elif stream_resp.status_code != 200:
                    error_bytes = await stream_resp.aread()
                    yield f"Error calling NVIDIA API (status {stream_resp.status_code}): {error_bytes.decode('utf-8')}"
                    return
                    
                async for line in stream_resp.aiter_lines():
                    if not line:
                        continue
                    if line.startswith("data: "):
                        data_str = line[6:]
                        if data_str.strip() == "[DONE]":
                            break
                        try:
                            import json
                            chunk_json = json.loads(data_str)
                            choices = chunk_json.get("choices", [])
                            if choices:
                                delta = choices[0].get("delta", {})
                                token = delta.get("content") or delta.get("reasoning_content") or ""
                                if token:
                                    yield token
                        except Exception:
                            pass
    except Exception as e:
        yield f"Connection Error: Failed to talk to NVIDIA API. {e}"

